/**
 * Regenerates THIRD-PARTY-NOTICES.md from the PRODUCTION dependency tree.
 *
 * The components we redistribute are permissively licensed — MIT, ISC, BSD —
 * and every one of those licences requires its copyright notice and permission
 * text to travel with the distribution. Our own licence is proprietary, which
 * changes nothing about that obligation.
 *
 * The tree is resolved the same way the image and the tarball resolve it, so
 * the file lists what actually ships and not what `package.json` mentions.
 *
 *   node scripts/third-party-notices.mjs           # write the file
 *   node scripts/third-party-notices.mjs --check   # fail if it is out of date
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'THIRD-PARTY-NOTICES.md');

const stage = mkdtempSync(join(tmpdir(), 'tpn-'));
try {
  for (const f of ['package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml'])
    writeFileSync(join(stage, f), readFileSync(join(ROOT, f)));
  execFileSync('pnpm', ['install', '--prod', '--frozen-lockfile', '--node-linker=hoisted',
    '--ignore-scripts', '--silent'], { cwd: stage, stdio: 'ignore' });

  const modules = join(stage, 'node_modules');
  const dirs = [];
  for (const name of readdirSync(modules).sort()) {
    if (name.startsWith('.')) continue;
    if (name.startsWith('@')) {
      for (const sub of readdirSync(join(modules, name)).sort()) dirs.push(`${name}/${sub}`);
    } else dirs.push(name);
  }

  const pkgs = [];
  for (const d of dirs) {
    const manifest = join(modules, d, 'package.json');
    if (!existsSync(manifest)) continue;
    const m = JSON.parse(readFileSync(manifest, 'utf8'));
    const licence = typeof m.license === 'string' ? m.license : m.license?.type ?? 'see notice';
    let text = '';
    for (const f of readdirSync(join(modules, d))) {
      if (/^(licen[cs]e|copying)(\.\w+)?$/i.test(f)) {
        text = readFileSync(join(modules, d, f), 'utf8').trim();
        break;
      }
    }
    // The copyright line is the part that must travel; the permission text is
    // identical across every copy of a given licence and is included once below.
    const copyright = (text.match(/^.*copyright.*$/im) ?? [''])[0].trim();
    pkgs.push({ name: m.name ?? d, version: m.version ?? '', licence, copyright, hasText: text !== '' });
  }

  const byLicence = new Map();
  for (const p of pkgs) byLicence.set(p.licence, (byLicence.get(p.licence) ?? 0) + 1);

  const lines = [
    '# Third-party notices',
    '',
    'The SYNERGY Ivanti MCP server is distributed with the components below. Each is',
    'licensed by its own authors under its own terms, which govern that component and',
    'are unaffected by the licence in [`LICENSE`](LICENSE).',
    '',
    'Every licence here requires its copyright notice to travel with the distribution,',
    'which is why this file ships inside the container image and the release tarball.',
    '',
    `Generated by \`node scripts/third-party-notices.mjs\` from the production dependency`,
    `tree — ${String(pkgs.length)} components, resolved exactly as the image resolves them.`,
    '',
    '| Licence | Components |',
    '|---|---|',
    ...[...byLicence.entries()].sort((a, b) => b[1] - a[1])
      .map(([l, n]) => `| ${l} | ${String(n)} |`),
    '',
    '## Components',
    '',
    '| Component | Version | Licence | Copyright |',
    '|---|---|---|---|',
    ...pkgs.map((p) => `| \`${p.name}\` | ${p.version} | ${p.licence} | ${p.copyright.replace(/\|/g, '\\|') || '—'} |`),
    '',
  ];
  const body = lines.join('\n');

  if (process.argv[2] === '--check') {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== body) {
      console.error('THIRD-PARTY-NOTICES.md is out of date. Run: node scripts/third-party-notices.mjs');
      process.exit(1);
    }
    console.log(`third-party notices up to date: ${String(pkgs.length)} components`);
  } else {
    writeFileSync(OUT, body);
    console.log(`wrote THIRD-PARTY-NOTICES.md — ${String(pkgs.length)} components`);
  }
} finally {
  rmSync(stage, { recursive: true, force: true });
}
